export function isSmartTelescopeRotatable(
  item?: { isSmartTelescope?: boolean; supportsSensorRotation?: boolean; name?: string } | null
): boolean {
  if (!item || !item.isSmartTelescope) return true;
  if (item.supportsSensorRotation) return true;
  if (item.name && /draco|드레이코/i.test(item.name)) return true;
  return false;
}

