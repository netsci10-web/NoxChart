import { EquipmentCategory } from '../types/astronomy';

export type TelescopeOpticalType = '굴절' | '반사' | '복합' | '기타';

export const TELESCOPE_OPTICAL_TYPES: TelescopeOpticalType[] = [
  '굴절',
  '반사',
  '복합',
  '기타',
];

export function normalizeTelescopeOpticalType(raw?: string): TelescopeOpticalType {
  if (!raw) return '굴절';
  const s = raw.trim().toLowerCase();
  if (s === '굴절' || s.includes('굴절') || s.includes('refractor') || s.includes('apo') || s.includes('ed')) {
    return '굴절';
  }
  if (
    s === '반사' ||
    s.includes('반사') ||
    s.includes('뉴턴') ||
    s.includes('돕소니언') ||
    s.includes('dob') ||
    s.includes('newton') ||
    s.includes('reflector') ||
    s.includes('rc')
  ) {
    return '반사';
  }
  if (
    s === '복합' ||
    s.includes('복합') ||
    s.includes('sct') ||
    s.includes('슈미트') ||
    s.includes('막스토프') ||
    s.includes('mak') ||
    s.includes('카세그레인') ||
    s.includes('edgehd') ||
    s.includes('rasa') ||
    s.includes('catadioptric')
  ) {
    return '복합';
  }
  return '기타';
}

